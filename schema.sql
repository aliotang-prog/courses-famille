CREATE TABLE IF NOT EXISTS families (code TEXT PRIMARY KEY, version INTEGER NOT NULL DEFAULT 1, data TEXT NOT NULL, updated INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS photos (id TEXT PRIMARY KEY, code TEXT NOT NULL, mime TEXT NOT NULL, b64 TEXT NOT NULL, created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS photos_code ON photos(code);
CREATE TABLE IF NOT EXISTS presence (code TEXT NOT NULL, conn TEXT NOT NULL, seen INTEGER NOT NULL, PRIMARY KEY (code, conn));
